// Dicionario portugues do Brasil (pt-BR) - cobertura completa das chaves de
// pl.ts, fallback en->pl conforme index.ts.
//
// Arquitetura (ver ADR-0132):
// - Um idioma por instalacao (escritorio de advocacia = um idioma).
// - Chaves ESPELHADAS em relacao a pl.ts. `pl` continua sendo a fonte das
//   chaves (TranslationKey gerado a partir de `pl`); chave ausente -> fallback
//   em `t()`.
// - Formato de data e feito pelo helper `formatDate` (locale-aware), nao no
//   dicionario.
//
// Terminologia (mercado brasileiro): sprawa -> processo/caso, pismo ->
// peticao, kancelaria -> escritorio de advocacia, mecenas -> Doutor(a) /
// Advogado(a) (forma de tratamento), umowa -> contrato, orzeczenie ->
// decisao/acordao, sad -> tribunal/vara, akta -> autos.
//
// REGRA RIGIDA (incidente anterior neste projeto - nao repetir):
// - Patron e um produto com escopo RGPD/UE (nao afirma conformidade com a
//   LGPD e nao tem funcionalidade especifica de LGPD). Onde pl.ts/en.ts
//   menciona RODO/GDPR, a traducao usa "RGPD" ou "proteção de dados"
//   generico - NUNCA "conforme a LGPD".
// - O pipeline de anonimizacao do produto reconhece identificadores
//   polacos especificos (PESEL/NIP/REGON), nao brasileiros. Descricoes
//   genericas do pipeline NAO trocam esses identificadores por CPF/CNPJ.

