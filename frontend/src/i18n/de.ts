// Slownik niemiecki (DE) - pelne pokrycie kluczy pl.ts, fallback en->pl wg index.ts.
//
// Architektura (patrz ADR-0132):
// - Jeden jezyk per instalacja (kancelaria = jeden jezyk). Locale wybierane w
//   konfiguracji instalacji, nie w URL.
// - Klucze LUSTRZANE wobec pl.ts. `pl` pozostaje zrodlem kluczy (TranslationKey
//   generowane z `pl`); brak klucza DE -> fallback w `t()`.
// - Format dat realizowany przez helper `formatDate` (locale-aware), nie w slowniku.
//
// Terminologia (rynek DE LegalTech, forma "Sie"):
// sprawa -> Akte/Mandat, pismo -> Schriftsatz, kancelaria -> Kanzlei,
